"""Every settings copy literal must be a three-language triple.

This is the source-level half of the trilingual contract: a call site that
still passes only Simplified + English would compile (the resolver needs three
arguments, so it would not) and, more importantly, no call site may fall back
to the blanket "any zh is Simplified" branch. The single language decision
lives in BlinkClipCore/SettingsStrings.swift.
"""
import pathlib, re, sys
root, out = map(pathlib.Path, sys.argv[1:])
COPY_NAMES = r'(?:SettingsCopy\.trilingual|PermissionCopy\.text|HistoryRetentionCopy\.text)'
CALL = re.compile(COPY_NAMES + r'\(')

def read_literal(text, index):
    assert text[index] == '"', text[index:index + 20]
    out, i = [], index + 1
    while i < len(text):
        ch = text[i]
        if ch == '\\':
            out.append(text[i:i + 2]); i += 2; continue
        if ch == '"':
            return ''.join(out), i + 1
        out.append(ch); i += 1
    raise SystemExit('unterminated literal')

files = sorted(p for p in (root / 'Sources/BlinkClip').rglob('*.swift'))
calls, problems = {name: [] for name in ('SettingsCopy', 'PermissionCopy', 'HistoryRetentionCopy')}, []
for path in files:
    if path.name == 'ScreenshotSettingsCopy.swift':
        continue  # its own provider, tracked by the copy-table structure gate
    text = path.read_text()
    position = 0
    while True:
        match = CALL.search(text, position)
        if not match:
            break
        owner = match.group(0).split('.')[0]
        cursor = match.end()
        arguments = []
        while True:
            while text[cursor].isspace():
                cursor += 1
            if text[cursor] != '"':
                problems.append(f'{path.name}: argument {len(arguments)} is not a string literal')
                break
            value, cursor = read_literal(text, cursor)
            arguments.append(value)
            while text[cursor].isspace():
                cursor += 1
            if text[cursor] == ')':
                cursor += 1
                break
            if text[cursor] != ',':
                problems.append(f'{path.name}: unexpected {text[cursor]!r} after argument {len(arguments)}')
                break
            cursor += 1
        if len(arguments) != 3:
            problems.append(f'{path.name}: {owner}.… has {len(arguments)} literal arguments, expected 3')
        else:
            calls[owner].append((path.name, arguments))
        position = cursor
assert not problems, problems

