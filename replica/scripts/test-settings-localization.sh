#!/bin/bash
set -euo pipefail
: "${ARTIFACT_TASK_DIR:?Run via storage-guard run --repo blinkclip --task settings-localization -- ...}"
replica_root="$(cd "$(dirname "$0")/.." && pwd)"
test_build="$ARTIFACT_TASK_DIR/build"
test_out="$ARTIFACT_TASK_DIR/out"
mkdir -p "$test_build/tmp" "$test_build/module-cache" "$test_out"
export TMPDIR="$test_build/tmp/"
export CLANG_MODULE_CACHE_PATH="$test_build/module-cache"
export SWIFT_MODULECACHE_PATH="$test_build/module-cache"
target="$(uname -m)-apple-macosx14.0"
core_root="$replica_root/Sources/BlinkClipCore"
# The settings copy providers import BlinkClipCore (SettingsStrings, the
# resource-key fallback), so the harness links a scratch Core module built from
# the shipping sources instead of a copy. Both copy providers resolve the
# language through the same SettingsLanguage, which is why the scratch module
# must contain it.
core_sources=("$core_root/SettingsStrings.swift" "$core_root/SettingsLocalization.swift" "$core_root/ResourceBundle.swift")
# `Bundle.module` is generated by SwiftPM only; the isolated harness supplies
# the same accessor so the production ResourceBundle file compiles unchanged.
shim="$test_build/BundleModuleShim.swift"
printf '%s\n' 'import Foundation' 'extension Bundle { static var module: Bundle { Bundle.main } }' > "$shim"
sources=("$replica_root/Sources/BlinkClip/UI/ScreenshotSettingsCopy.swift"
         "$replica_root/Sources/BlinkClip/UI/SettingsCopy.swift"
         "$replica_root/Tests/Native/SettingsLocalizationHarness.swift")
shasum -a 256 "${sources[@]}" "${core_sources[@]}" > "$test_out/production-inputs.sha256"
xcrun swiftc -swift-version 5 -target "$target" -module-cache-path "$test_build/module-cache" \
  -emit-library -emit-module -module-name BlinkClipCore "${core_sources[@]}" "$shim" \
  -emit-module-path "$test_build/BlinkClipCore.swiftmodule" \
  -o "$test_build/libBlinkClipCore.dylib" > "$test_out/core-compile.log" 2>&1
xcrun swiftc -parse-as-library -swift-version 5 -target "$target" \
  -module-cache-path "$test_build/module-cache" \
  -I "$test_build" -L "$test_build" -lBlinkClipCore -Xlinker -rpath -Xlinker "$test_build" \
  "${sources[@]}" \
  -o "$test_build/settings-localization" > "$test_out/compile.log" 2>&1
languages=(en zh-Hans zh-Hant)
for language in "${languages[@]}"; do
  "$test_build/settings-localization" "$language" "$test_out/$language.json" \
    -AppleLanguages "($language)" > "$test_out/$language.log" 2>&1
  cat "$test_out/$language.log"
done
