    public nonisolated static func originalPasteboardItems(from payloads: [String: Data]) throws -> [PasteboardItem] {
        let items: [PasteboardItem]
        if let data = payloads[originalItemDataPayloadKey] {
            items = PasteboardDataCodec.decodeItems(data)
        } else if let data = payloads[multiItemPayloadKey] {
            if let ordered = try? JSONDecoder().decode([PasteboardItem].self, from: data) {
                items = ordered
            } else {
                let legacy = try JSONDecoder().decode([[String: Data]].self, from: data)
                items = legacy.map { values in
                    let object = PasteboardItem()
                    for (type, data) in values { object.setData(data, forType: type) }
                    return object
                }
            }
        } else {
            let object: PasteboardItem
            if let data = payloads[orderedTypesPayloadKey] {
                object = PasteboardItem(types: try JSONDecoder().decode([String].self, from: data),
                                               dataByType: payloads)
            } else {
                object = PasteboardItem()
                for (type, data) in payloads { object.setData(data, forType: type) }
            }
            items = [object]
        }
        for item in items {
            for type in analysisPayloadKeys.union([multiItemPayloadKey, orderedTypesPayloadKey, originalItemDataPayloadKey]) { item.removeData(type) }
        }
        return items
    }

    /// routes every classified kind.
    /// The archive route is restored; native archive bytes/class identity are not proven equivalent.
    public nonisolated static func knownPasteboardChecksum(from payloads: [String: Data]) throws -> String? {
        let items = try originalPasteboardItems(from: payloads)
        let kind = PasteboardClassification.classifyItems(items)
        return PasteboardChecksums.checksumForItems(items, kind: kind)
    }

    /// Payloads without any pasteboard representation carry no content identity. The
    /// archive checksum of that empty item set is one constant, so using it to identify
    /// items merges unrelated entries. Callers fall back to kind/text/representation
    /// equality for these items instead.
    nonisolated static func hasPasteboardContent(_ payloads: [String: Data]) -> Bool {
        PasteboardChecksums.hasContent((try? originalPasteboardItems(from: payloads)) ?? [])
    }

    nonisolated static func contentChecksum(from payloads: [String: Data]) -> String? {
        guard hasPasteboardContent(payloads) else { return nil }
        return try? knownPasteboardChecksum(from: payloads)
    }

    nonisolated static func projectNativePasteboardItems(_ raw: Data, onto previous: [String: Data]) throws -> [String: Data] {
        let items = PasteboardDataCodec.decodeItems(raw)
        var payloads = previous.filter { analysisPayloadKeys.contains($0.key) }
        if let first = items.first {
            for type in first.currentOrderedTypes() {
                if let data = first.dataForType(forType: type) { payloads[type] = data }
            }
            if let order = previous[orderedTypesPayloadKey] {
                payloads[orderedTypesPayloadKey] = (try? JSONDecoder().decode([String].self, from: order)) == first.currentOrderedTypes()
                    ? order : try JSONEncoder().encode(first.currentOrderedTypes())
            }
        }
        if previous[multiItemPayloadKey] != nil {
            let before = try? originalPasteboardItems(from: previous)
            if let before, before.count == items.count, zip(before, items).allSatisfy({ old, new in
                let types = old.currentOrderedTypes()
                return types == new.currentOrderedTypes() && types.allSatisfy {
                    old.dataForType(forType: $0) == new.dataForType(forType: $0)
                }
            }) {
                payloads[multiItemPayloadKey] = previous[multiItemPayloadKey]
            } else {
                let encoder = JSONEncoder(); encoder.outputFormatting = [.sortedKeys]
                payloads[multiItemPayloadKey] = try encoder.encode(items)
            }
        } else if previous[originalItemDataPayloadKey] != nil || items.count > 1 {
            payloads[originalItemDataPayloadKey] = raw
        }
        return payloads
    }

    public nonisolated static func pasteboardImage(from payloads: [String: Data]) -> NSImage? {
        for values in normalizedPasteboardPayloads(payloads) {
            let item = PasteboardItem()
            for (type, data) in values { item.setData(data, forType: type) }
            if let image = item.image() { return image }
        }
        return nil
    }

    public nonisolated static func normalizedPasteboardPayloads(_ payloads: [String: Data]) -> [[String: Data]] {
        func cleaned(_ values: [String: Data]) -> [String: Data] {
            values.filter { !analysisPayloadKeys.contains($0.key) && $0.key != orderedTypesPayloadKey }
        }
        func normalizedItems(_ items: [PasteboardItem]) -> [[String: Data]] {
            items.map { item in
                var values: [String: Data] = [:]
                for type in item.currentOrderedTypes() {
                    guard type != multiItemPayloadKey, type != originalItemDataPayloadKey,
                          let data = item.dataForType(forType: type) else { continue }
                    values[type] = data
                }
                return cleaned(values)
            }
        }
        if let data = payloads[originalItemDataPayloadKey] {
            if let items = PasteboardDataCodec.decodeIfValid(data) { return normalizedItems(items) }
            // Preserve corrupt bytes in the identity instead of equating every failed decode with [].
            return [cleaned(payloads)]
        }
        if let data = payloads[multiItemPayloadKey] {
            if let ordered = try? JSONDecoder().decode([PasteboardItem].self, from: data) {
                return normalizedItems(ordered)
            }
            if let legacy = try? JSONDecoder().decode([[String: Data]].self, from: data) {
                return legacy.map(cleaned)
            }
        }
        return [cleaned(payloads)]
    }

    nonisolated static func hasValidExplicitPasteboardRepresentations(_ payloads: [String: Data]) -> Bool {
        if let data = payloads[originalItemDataPayloadKey] {
            return PasteboardDataCodec.decodeIfValid(data) != nil
        }
        guard payloads[multiItemPayloadKey] != nil || payloads[orderedTypesPayloadKey] != nil else { return false }
        return (try? originalPasteboardItems(from: payloads)) != nil
    }

    nonisolated static func hasSamePasteboardRepresentations(_ first: [String: Data], _ second: [String: Data]) -> Bool {
        let containers = [originalItemDataPayloadKey, multiItemPayloadKey, orderedTypesPayloadKey]
        guard containers.contains(where: { first[$0] != nil || second[$0] != nil }) else {
            return normalizedPasteboardPayloads(first) == normalizedPasteboardPayloads(second)
        }
        if [first, second].contains(where: { payloads in
            payloads[originalItemDataPayloadKey].map { PasteboardDataCodec.decodeIfValid($0) == nil } ?? false
        }) {
            return first.filter { !analysisPayloadKeys.contains($0.key) }
                == second.filter { !analysisPayloadKeys.contains($0.key) }
        }
        do {
            let encoder = JSONEncoder()
            encoder.outputFormatting = [.sortedKeys]
            return try encoder.encode(originalPasteboardItems(from: first))
                == encoder.encode(originalPasteboardItems(from: second))
        } catch {
            return false
        }
    }

    @discardableResult
    public func capture(pasteboard: NSPasteboard, sourceName: String, sourceBundleID: String?,
                        snapshot: [PasteboardItem]? = nil, respectMonitoringPolicy: Bool = true,
                        sourceApplication: SourceApplicationRecord? = nil) throws -> UUID? {
        try captureWithInsertionResult(pasteboard: pasteboard, sourceName: sourceName,
            sourceBundleID: sourceBundleID, snapshot: snapshot, respectMonitoringPolicy: respectMonitoringPolicy,
            sourceApplication: sourceApplication)?.id
    }

    func captureWithInsertionResult(pasteboard: NSPasteboard, sourceName: String, sourceBundleID: String?,
                                    snapshot: [PasteboardItem]? = nil, respectMonitoringPolicy: Bool = true,
                                    sourceApplication: SourceApplicationRecord? = nil,
                                    sourceProvider: (() -> (name: String, bundleID: String?, application: SourceApplicationRecord?))? = nil) throws -> (id: UUID, isNew: Bool)? {
        let rawItems = snapshot == nil ? pasteboard.pasteboardItems ?? [] : []
        let types = Set(snapshot?.flatMap { $0.currentOrderedTypes() } ?? rawItems.flatMap { $0.types.map(\.rawValue) })
        if respectMonitoringPolicy {
            guard try allowsPasteboardCapture(types: types, sourceBundleID: sourceBundleID) else { return nil }
        }
        let capturedItems = (snapshot ?? rawItems.map { item -> PasteboardItem in
            let captured = PasteboardItem()
            for type in item.types {
                if let data = item.data(forType: type) {
                    captured.setValue(data, forType: type.rawValue)
                } else {
                    captured.setData(nil, forType: type.rawValue)
                }
            }
            return captured
        }).map { item -> PasteboardItem in
            for type in Self.analysisPayloadKeys.union([multiItemPayloadKey, orderedTypesPayloadKey, originalItemDataPayloadKey]) {
                item.removeData(type)
            }
            return item
        }
        var representations = capturedItems.map { item -> [String: Data] in
            var values: [String: Data] = [:]
            for type in item.currentOrderedTypes() {
                if let data = item.dataForType(forType: type) { values[type] = data }
            }
            return values
        }
        representations.removeAll(where: \.isEmpty)
        guard var payloads = representations.first else { return nil }
        if let first = capturedItems.first(where: { item in
            item.currentOrderedTypes().contains { item.dataForType(forType: $0) != nil }
        }) {
            payloads[orderedTypesPayloadKey] = try JSONEncoder().encode(first.currentOrderedTypes())
        }
        if capturedItems.count > 1 {
            payloads[originalItemDataPayloadKey] = PasteboardDataCodec.encodeItems(capturedItems, useBinaryPlist: preferences.useBinaryPlist)
        }
        let fileStrings = capturedItems.compactMap { item -> String? in
            guard let string = item.stringForType(forType: NSPasteboard.PasteboardType.fileURL.rawValue) else { return nil }
            return item.fileURL()?.path ?? string
        }
        var plainText = capturedItems.lazy.compactMap { $0.plainTextString() }.first
        if snapshot == nil {
            plainText = plainText ?? pasteboard.string(forType: .string) ?? pasteboard.string(forType: .URL)
        }
        if !fileStrings.isEmpty { plainText = fileStrings.joined(separator: "\n") }
        if plainText == nil {
            for item in capturedItems {
                if let rich = item.attributedString() {
                    plainText = rich.string
                    break
                }
            }
        }
        let richTypes: Set<String> = [NSPasteboard.PasteboardType.rtf.rawValue,
                                      NSPasteboard.PasteboardType.rtfd.rawValue,
                                      NSPasteboard.PasteboardType.html.rawValue]
        let kind: ClipboardKind
        switch PasteboardClassification.classifyItems(capturedItems) {
        case .files: kind = .files
        case .image: kind = .image
        case .color: kind = .color
        case .link: kind = .link
        case .text: kind = types.isDisjoint(with: richTypes) ? .text : .richText
        case .unknown:
            if snapshot != nil { kind = .unknown }
            else if types.contains("NSFilenamesPboardType") { kind = .files }
            else if types.contains(NSPasteboard.PasteboardType.color.rawValue) { kind = .color }
            else if !types.isDisjoint(with: richTypes) { kind = .richText }
            else { kind = .unknown }
        }
        let result = try addWithInsertionResult(ClipboardItem(title: "", kind: kind, plainText: plainText, sourceName: sourceName,
                                       sourceBundleID: sourceBundleID, payloads: payloads),
                         sourceApplication: sourceApplication, recordCapture: true,
                         sourceProvider: sourceProvider)
        if kind == .image { startBackgroundTextRecognition(id: result.id) }
        return result
    }

    public func importPasteboardItems(_ data: Data, sourceName: String) throws -> UUID? {
        let snapshot = try PasteboardArchive.decodeItems(data)
        // A supplied snapshot never reads or changes the system pasteboard.
        return try capture(pasteboard: .general, sourceName: sourceName, sourceBundleID: nil,
                           snapshot: snapshot, respectMonitoringPolicy: false)
    }

    fileprivate func allowsPasteboardCapture(types: Set<String>, sourceBundleID: String?) throws -> Bool {
        guard !types.isEmpty, !types.contains(replicaGeneratedType.rawValue) else { return false }
        // Check policy before reading promised data, including in the timer path.
        if preferences.ignoreTransientContent && !types.isDisjoint(with: transientTypes) { return false }
        if preferences.ignoreConcealedContent && !types.isDisjoint(with: concealedTypes) { return false }
        if let sourceBundleID, preferences.excludedBundleIDs.contains(sourceBundleID) { return false }
        if let until = preferences.pauseUntil {
            if until > Date() { return false }
            preferences.pauseUntil = nil
            preferences.isMonitoringPaused = false
            try save()
        } else if preferences.isMonitoringPaused {
            return false
        }
        return true
    }

    /// Prepares native drag groups without writing a pasteboard or performing restore bookkeeping.
    public func dragPasteboardGroups(for selected: [ClipboardItem],
                                     options: PasteboardRestore.Options) throws -> [[PasteboardItem]] {
        let selections = try selected.map { item -> PasteboardRestore.Selection in
            let application = sourceApplication(for: item)
            let kind: PasteboardContentKind
            switch item.kind {
            case .text, .richText: kind = .text
            case .link: kind = .link
            case .image: kind = .image
            case .files: kind = .files
            case .color: kind = .color
            case .unknown: kind = .unknown
            }
            let representations: [PasteboardItem]
            if !PasteboardRestore.usesPlainProjection(kind: kind, options: options), kind == .image {
                representations = try Self.imageRestore.prepare(sourceName: application?.name,
                    timestamp: item.isInHistory ? item.createdAt : nil) {
                        try Self.originalPasteboardItems(from: item.payloads)
                    }
            } else {
                representations = try Self.originalPasteboardItems(from: item.payloads)
            }
            return .init(kind: kind, items: representations, sourceBundleID: application?.bundleIdentifier)
        }
        return PasteboardRestore.itemsFromSelections(selections, options: options,
                                                     removingTypesContaining: ["com.microsoft.ole.source"])
    }

