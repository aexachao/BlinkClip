    public nonisolated static func ordinaryRestoreRepresentations(for item: ClipboardItem,
                                                                plainTextProjection: Bool) throws -> [PasteboardItem] {
        var representations = try originalPasteboardItems(from: item.payloads)
        let allowsLegacyText = item.payloads[originalItemDataPayloadKey] == nil
            && item.payloads[orderedTypesPayloadKey] == nil
            && item.payloads[multiItemPayloadKey] == nil
        for object in representations {
            for type in analysisPayloadKeys.union([multiItemPayloadKey, orderedTypesPayloadKey, originalItemDataPayloadKey]) {
                object.removeData(type)
            }
            if allowsLegacyText, object.currentOrderedTypes().isEmpty, let text = item.plainText {
                object.setString(text, forType: NSPasteboard.PasteboardType.string.rawValue)
            }
        }
        // Explicit representation containers are authoritative; legacy display text must not replace them.
        if allowsLegacyText, plainTextProjection,
           PasteboardRestore.textOnlyItems(representations).isEmpty, let text = item.plainText {
            representations = [PasteboardItem.itemWithString(text)]
        }
        return representations
    }

    private func writeToPasteboard(ids: [UUID], pasteboard: NSPasteboard,
                                   options: PasteboardRestore.Options, recognizedImageData: Data?,
                                   resolvedSelection: [ClipboardItem]? = nil) throws {
        guard !ids.isEmpty else { return }
        let selected: [ClipboardItem]
        if let resolvedSelection {
            selected = resolvedSelection
        } else {
            // Identifier-only compatibility callers resolve their inputs before the shared writer.
            try reload()
            selected = try ids.map { id -> ClipboardItem in
                guard let item = items.first(where: { $0.id == id && !$0.isDeleted }) else { throw ClipboardStoreError.itemNotFound }
                return item
            }
        }
        let selections = try selected.map { item -> PasteboardRestore.Selection in
            let application = sourceApplication(for: item)
            let kind: PasteboardContentKind
            switch item.kind {
            case .text, .richText: kind = .text
            case .link: kind = .link
            case .image: kind = .image
            case .files: kind = .files
            case .color: kind = .color
            case .unknown: kind = .unknown
            }
            let plain = PasteboardRestore.usesPlainProjection(kind: kind, options: options)
            var representations: [PasteboardItem]
            if let recognizedImageData {
                guard kind == .image, item.imageData == recognizedImageData else { throw RecognizedImageTextCopyError.imageChanged }
                guard let text = item.recognizedText, !text.isEmpty else { throw RecognizedImageTextCopyError.noRecognizedText }
                representations = [PasteboardItem.itemWithString(text)]
            } else if !plain, kind == .image {
                representations = try Self.imageRestore.prepare(sourceName: application?.name,
                    timestamp: item.isInHistory ? item.createdAt : nil) {
                        try Self.ordinaryRestoreRepresentations(for: item, plainTextProjection: plain)
                    }
            } else {
                representations = try Self.ordinaryRestoreRepresentations(for: item, plainTextProjection: plain)
            }
            return .init(kind: kind, items: representations, sourceBundleID: application?.bundleIdentifier)
        }
        let objects = PasteboardRestore.itemsFromSelections(selections, options: options,
            removingTypesContaining: ["com.microsoft.ole.source"]).flatMap { $0 }
        try finishPasteboardWrite(objects, pasteboard: pasteboard) {
            try prepareHistoryRestore(selected)
        }
    }

    private func finishPasteboardWrite(_ objects: [PasteboardItem], pasteboard: NSPasteboard,
                                       prepareRestoration: () throws -> HistoryRestoreOperation) throws {
        if let first = objects.first {
            first.setData(Data(), forType: generatedType.rawValue)
            first.setData(Data(), forType: replicaGeneratedType.rawValue)
        }
        // The original writer clears and writes even when processing produced no representations.
        let writeSucceeded: Bool
        if let state = PasteboardCaptureState.current(for: pasteboard),
           state.pasteboard === pasteboard {
            state.writeItems(objects)
            writeSucceeded = state.lastWriteSucceeded
        } else {
            let writer = PasteboardWriter(pasteboard: pasteboard)
            writer.writeItems(objects)
            writeSucceeded = writer.lastWriteSucceeded
        }
        if let state = PasteboardCaptureState.current(for: pasteboard) {
            state.persistChangeCount?(state.lastChangeCount)
        }
        guard writeSucceeded else { throw PasteboardWriteError.writeFailed }
        // performAndWait + save, then undo cleanup and DidRestore, before deactivation.
        // A failed commit must reach the caller: the pasteboard bytes are already written,
        // but undo cleanup and DidRestore must not report a persisted restore.
        let restoration = try prepareRestoration()
        try recordRestoredSelection(restoration)
        Self.restoreUndoManager.resolveValue().removeAllActions()
        // 37a144 posts process-wide with the restoring manager as object.
        // Keep the legacy subject for the existing local sound subscriber.
        NotificationCenter.default.post(name: Self.didRestoreItemNotification, object: self)
        didRestoreItem.send()
    }
}

@MainActor
public final class ClipboardMonitor: NSObject, PasteboardCaptureDelegate {
    @MainActor
    private final class TimerTarget: NSObject {
        weak var monitor: ClipboardMonitor?

        init(_ monitor: ClipboardMonitor) {
            self.monitor = monitor
            super.init()
        }

        @objc func handlePollTimer(_ timer: Timer) {
            monitor?.handlePollTimer(timer)
        }

        @objc func handleSyncTimer(_ timer: Timer) {
            monitor?.handleSyncTimer(timer)
        }
    }

    private lazy var timerTarget = TimerTarget(self)
    private let store: ClipboardStore
    private let captureState: PasteboardCaptureState
    private let defaults: UserDefaults
    private let undoManagerDependency = Dependency(\DependencyValues.pasteboardUndoManager)
    private let historyDiagnostics = NamedDiagnostic.makeNamedDiagnostic(name: "PasteboardHistoryManager")
    public static let didSynchronizeNotification = Notification.Name("pasteboardHistoryManagerDidSync")
    public static let didChangeStatusNotification = Notification.Name("pasteboardHistoryManagerDidChangeStatus")
    public static let didCreateItemNotification = Notification.Name("pasteboardHistoryManagerDidCreateItem")
    public static let didCaptureItemNotification = Notification.Name("pasteboardHistoryManagerDidCaptureItem")
    private var pasteboard: NSPasteboard { captureState.pasteboard }
    private var timer: Timer? {
        get { captureState.pollTimer }
        set { captureState.pollTimer = newValue }
    }
    private var syncTimer: Timer? {
        get { captureState.syncTimer }
        set { captureState.syncTimer = newValue }
    }
    private var lastChangeCount: Int {
        get { captureState.lastChangeCount }
        set { captureState.lastChangeCount = newValue }
    }
    private func recordMonitoring(_ message: String) {
        captureState.loggingDependency.resolve().record(scope: "pasteboard.monitoring", message: message)
    }

    private func recordSynchronization(_ message: String) {
        captureState.loggingDependency.resolve().record(scope: "pasteboard.syncronize", message: message)
    }
    public private(set) var lastError: Error?
    public var onCapture: ((UUID) -> Void)?

    public init(store: ClipboardStore, pasteboard: NSPasteboard = .general, initialChangeCount: Int = 0,
                defaults: UserDefaults = .standard) {
        self.store = store
        self.defaults = defaults
        let savedCount = initialChangeCount == 0 ? defaults.integer(forKey: "pasteboard-change-token") : initialChangeCount
        self.captureState = PasteboardCaptureState.makePasteboardCaptureState(changeCount: savedCount, pasteboard: pasteboard)
        super.init()
        captureState.delegate = self
        captureState.persistChangeCount = { [defaults] count in
            defaults.set(count, forKey: "pasteboard-change-token")
        }
        if defaults.integer(forKey: "pasteboard-change-token") == 0 {
            defaults.set(captureState.lastChangeCount, forKey: "pasteboard-change-token")
        }
        PasteboardCaptureState.register(captureState)
    }

    public func start() {
        startMonitoringWithNotification()
    }

    public func startMonitoringWithNotification() {
        performAndPostStatusChange(startMonitoring)
    }

    public func performAndPostStatusChange(_ action: () -> Void) {
        withExtendedLifetime(captureState, action)
        NotificationCenter.default.post(name: Self.didChangeStatusNotification, object: self)
    }

    public func startMonitoring() {
        recordMonitoring("Start monitoring pasteboard")
        guard timer == nil else { return }
        lastChangeCount = pasteboard.changeCount
        timer = Timer.scheduledTimer(timeInterval: 0.25, target: timerTarget,
                                     selector: #selector(TimerTarget.handlePollTimer(_:)), userInfo: nil, repeats: true)
        timer?.tolerance = 0.025
    }

    @objc private func handlePollTimer(_ timer: Timer) {
        poll()
    }

    public func stop() {
        stopMonitoringWithNotification()
    }

    public func stopMonitoringWithNotification() {
        performAndPostStatusChange(stopMonitoring)
    }

    public func stopMonitoring() {
        recordMonitoring("Stop monitoring pasteboard")
        timer?.invalidate()
        timer = nil
        syncTimer?.invalidate()
        syncTimer = nil
    }

    public func poll() {
        pollForChanges()
    }

    public func pollForChanges() {
        let count = pasteboard.changeCount
        guard count != lastChangeCount else { return }
        recordMonitoring("Pasteboard change detected, starting sync timer")
        lastChangeCount = pasteboard.changeCount
        syncTimer?.invalidate()
        syncTimer = Timer.scheduledTimer(timeInterval: 0.3, target: timerTarget,
                                         selector: #selector(TimerTarget.handleSyncTimer(_:)), userInfo: nil, repeats: false)
    }

    @objc private func handleSyncTimer(_ timer: Timer) {
        recordMonitoring("Sync timer fired")
        synchronizePasteboard()
    }

    public func originalPasteboardShouldRead(_ types: [String]) throws -> Bool {
        // reads the current policy without refreshing persistent history.
        var ignoredTypes = Set(store.preferences.ignoredPasteboardTypes)
        if store.preferences.ignoreTransientContent { ignoredTypes.formUnion(transientTypes) }
        if store.preferences.ignoreConcealedContent { ignoredTypes.formUnion(concealedTypes) }
        guard PasteboardPolicies.shouldCaptureChange(allTypes: types,
                                                     excludedApplications: Set(store.preferences.excludedBundleIDs),
                                                     ignoredTypes: ignoredTypes,
                                                     diagnostics: historyDiagnostics) else { return false }
        return try store.allowsPasteboardCapture(types: Set(types),
                                                sourceBundleID: NSWorkspace.shared.frontmostApplication?.bundleIdentifier)
    }

    public func originalPasteboardDidRead(_ state: PasteboardCaptureState) {
        persistCaptureState(state)
    }

    public func syncCount() -> Int {
        defaults.integer(forKey: "pasteboardSyncCount")
    }

    public func persistCaptureState(_ state: PasteboardCaptureState) {
        defaults.set(state.lastChangeCount, forKey: "pasteboard-change-token")
        let next = syncCount().addingReportingOverflow(1)
        precondition(!next.overflow, "Pasteboard sync count overflow")
        defaults.set(next.partialValue, forKey: "pasteboardSyncCount")
        NotificationCenter.default.post(name: Self.didSynchronizeNotification, object: self)
        guard !state.items.isEmpty else {
            historyDiagnostics.diagnosticSink().emitDebug("Empty pasteboard content")
            return
        }
        createItems(state.items)
    }

    public func createItems(_ items: [PasteboardItem]) {
        let created: Bool
        do {
            created = try createItem(items)
        } catch {
            lastError = error
            historyDiagnostics.diagnosticSink().emitError("Error creating item for pasteboard content")
            return
        }
        undoManagerDependency.resolveValue().removeAllActions()
        if created {
            NotificationCenter.default.post(name: Self.didCreateItemNotification, object: self)
        }
        NotificationCenter.default.post(name: Self.didCaptureItemNotification, object: self)
    }

    public func createItem(_ items: [PasteboardItem]) throws -> Bool {
        guard !items.isEmpty else { throw PasteboardItemCreationError.emptyContent }
        guard PasteboardChecksums.checksumForItems(items,
                                                      kind: PasteboardClassification.classifyItems(items)) != nil else {
            throw PasteboardItemCreationError.unsupportedContent
        }
        guard let captured = try store.captureWithInsertionResult(pasteboard: pasteboard, sourceName: "未知应用",
                                               sourceBundleID: nil, snapshot: items,
                                               respectMonitoringPolicy: false,
                                               sourceProvider: {
                                                   let app = NSWorkspace.shared.frontmostApplication
                                                   return (app?.localizedName ?? "未知应用", app?.bundleIdentifier,
                                                           SourceApplication.snapshot(app))
                                               }) else {
            throw PasteboardItemCreationError.unsupportedContent
        }
        onCapture?(captured.id)
        return captured.isNew
    }

    private func synchronizePasteboard() {
        let app = NSWorkspace.shared.frontmostApplication
        let sourceBundleID = app?.bundleIdentifier
        recordSynchronization("Starting Pasteboard sync from \(sourceBundleID ?? "unknown")")
        lastChangeCount = pasteboard.changeCount
        captureState.items = []
        _ = pasteboard.types
        guard PasteboardPolicies.permitsBackgroundRead(pasteboard) else {
            if let delegate = captureState.delegate {
                NotificationCenter.default.post(name: PasteboardPolicies.accessRequestNotification, object: delegate)
            }
            return
        }
        do {
            guard let rawItems = pasteboard.pasteboardItems else {
                recordSynchronization("No items in system pasteboard")
                captureState.diagnostics.diagnosticSink().emitFault("Error reading system pasteboard items")
                return
            }
            let allTypes = rawItems.flatMap { $0.types.map(\.rawValue) }
            recordSynchronization("Retrieved \(allTypes.count) types: \(allTypes.joined(separator: ", "))")
            if let delegate = captureState.delegate, try !delegate.originalPasteboardShouldRead(allTypes) {
                recordSynchronization("Cancelling pasteboard sync by delegate")
                return
            }
            var totalBytes = 0
            recordSynchronization("Start processing pasteboard items")
            for rawItem in rawItems {
                let item = PasteboardItem()
                for type in rawItem.types {
                    guard PasteboardPolicies.permitsRemoteType(type.rawValue, allTypes: allTypes) else { continue }
                    if let delegate = captureState.delegate {
                        let shouldRead = withExtendedLifetime(delegate) {
                            PasteboardPolicies.shouldCaptureType(type: type.rawValue, allTypes: allTypes)
                        }
                        guard shouldRead else { continue }
                    }
                    recordSynchronization("Getting data for type \(type.rawValue)")
                    guard let data = rawItem.data(forType: type) else { continue }
                    let size = totalBytes.addingReportingOverflow(data.count)
                    precondition(!size.overflow, "Pasteboard data size overflow")
                    guard size.partialValue <= 0x40000000 else {
                        captureState.diagnostics.diagnosticSink().emitError(
                            "Skipping pasteboard type \(type.rawValue): \(data.count) bytes exceeds the storable item size")
                        recordSynchronization("Skipped oversized data (\(data.count) bytes) for type \(type.rawValue)")
                        continue
                    }
                    totalBytes = size.partialValue
                    item.setValue(data, forType: type.rawValue)
                }
                if !item.currentOrderedTypes().isEmpty { captureState.items.append(item) }
            }
            do {
                defer { captureState.items = [] }
                recordSynchronization("Pasteboard sync completed, sending delegate callback")
                lastError = nil
                if let delegate = captureState.delegate { try delegate.originalPasteboardDidRead(captureState) }
            }
            recordSynchronization("All done")
        } catch {
            lastError = error
        }
    }

    deinit {
        MainActor.assumeIsolated {
            captureState.delegate = nil
            stopMonitoringWithNotification()
        }
    }
}
